    private void CalcularMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CalcularMouseClicked
        double taxa = 0;
        double seguro = 0;
        double total = 0;
        
        double valorFipe = Double.parseDouble(FIPE.getText());
        int idade = Integer.parseInt(Idade.getText());
        
        if(Nome.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Preencha o nome");
            return;
        }
        
        if(Idade.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Preencha a idade");
            return;
        }
        
        if(FIPE.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Informe valor da fipe");
            return;
        }
        
        if(idade < 0){
            JOptionPane.showMessageDialog(null,"Idade invalida");
            return;
        }
        
        if(Comercial.isSelected()){
            taxa = 0.020;
        }
        
        if(idade < 25){
            taxa += 0.015;
        }
        
        if(SeguroVidro.isSelected()){
            seguro += 180;
        }
        
        if(CarroReserva.isSelected()){
            seguro += 320;
        }
        
        total = (taxa * valorFipe) + seguro;
        
        JOptionPane.showMessageDialog(null, "Valor total a pagar: R$ " + total);
    }//GEN-LAST:event_CalcularMouseClicked

