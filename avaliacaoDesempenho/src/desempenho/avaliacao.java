    private void avaliarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_avaliarMouseClicked
    // Verificar campos vazios
    if (Nome.getText().trim().isEmpty()
            || Falta.getText().trim().isEmpty()
            || NotaProdutividade.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(null,
                "Preencha todos os campos!");
        return;
    }

    double nota;
    int faltas;

    // Converter os valores
    try {
        nota = Double.parseDouble(NotaProdutividade.getText().replace(",", "."));

        faltas = Integer.parseInt(Falta.getText());

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null,"Digite valores numéricos válidos!");
        return;
    }

    // Validar nota
    if (nota < 0 || nota > 10) {
        JOptionPane.showMessageDialog(null,"A nota deve estar entre 0 e 10!");
        return;
    }

    // Validar faltas
    if (faltas < 0) {
        JOptionPane.showMessageDialog(null,"O número de faltas não pode ser negativo!");
        return;
    }

    // Identificar o cargo
    String cargo;

    if (Analista.isSelected()) {
        cargo = "Analista";
    } else if (Dev.isSelected()) {
        cargo = "Desenvolvedor";
    } else if (Suporte.isSelected()) {
        cargo = "Suporte";
    } else {
        JOptionPane.showMessageDialog(null,"Selecione um cargo!");
        return;
    }

    // Criar funcionário
    funcionarioAtual = new Funcionario(
            Nome.getText().trim(), cargo);

    // Criar avaliação
    AvaliacaoDesempenho avaliacao = new AvaliacaoDesempenho(
            nota,
            faltas,
            cumpriumeta.isSelected(),
            realizoutreinamento.isSelected(),
            participouprojeto.isSelected()
    );

    // Calcular resultado
    resultadoAtual = avaliacao.calcularAvaliacao();

    faltasAtual = faltas;

    // Armazenar critérios atendidos
    criteriosAtual = "";

    if (cumpriumeta.isSelected()) {
        criteriosAtual += "Cumpriu metas; ";
    }

    if (realizoutreinamento.isSelected()) {
        criteriosAtual += "Realizou treinamento; ";
    }

    if (participouprojeto.isSelected()) {
        criteriosAtual += "Participou de projetos; ";
    }

    if (criteriosAtual.isEmpty()) {
        criteriosAtual = "Nenhum critério adicional atendido";
    }

    // Exibir resultado
    JOptionPane.showMessageDialog(null,
            "Pontuação final: "
            + resultadoAtual.getPontuacaoFinal()
            + "\nClassificação: "
            + resultadoAtual.getClassificacao());

    }//GEN-LAST:event_avaliarMouseClicked

    private void limparMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_limparMouseClicked
        Nome.setText("");
        Falta.setText("");
        NotaProdutividade.setText("");

        // Limpar seleção do cargo
        grupoCargo.clearSelection();

        // Desmarcar critérios
        cumpriumeta.setSelected(false);
        realizoutreinamento.setSelected(false);
        participouprojeto.setSelected(false);

        // Limpar dados da avaliação anterior
        funcionarioAtual = null;
        resultadoAtual = null;
        faltasAtual = 0;
        criteriosAtual = "";
    }//GEN-LAST:event_limparMouseClicked

    private void relatorioMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_relatorioMouseClicked
        // Verificar se existe uma avaliação
        if (resultadoAtual == null || funcionarioAtual == null) {
            JOptionPane.showMessageDialog(null,"Primeiro realize uma avaliação!");
            return;
        }

    // Criar relatório
        RelatorioAvaliacao relatorio = new RelatorioAvaliacao();

        String texto = relatorio.gerarRelatorio(
            funcionarioAtual,
            resultadoAtual,
            faltasAtual,
            criteriosAtual
        );

        // Exibir relatório
        JOptionPane.showMessageDialog(null, texto);
    }//GEN-LAST:event_relatorioMouseClicked

