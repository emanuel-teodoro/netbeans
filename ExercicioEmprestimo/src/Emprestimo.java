    private void CalcularMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CalcularMouseClicked
        double soma = 0;
        double taxa = 0;
        double seguro = 0;
        String parcela = ComboBox.getSelectedItem().toString();
        
        double valor = Double.parseDouble(ValorEmprestimo.getText());
        if(valor < 1000 || valor > 100000){
            JOptionPane.showMessageDialog(this, "Valor deve ser entre 1000 e 100000");
        }
        
        int meses = Integer.parseInt(ComboBox.getSelectedItem().toString());
        
        if(Comum.isSelected()){
            taxa = 0.025;
        }
        
        if(Servidor.isSelected()){
            taxa = 0.018;
        }
        
        if(Universitario.isSelected()){
            taxa = 0.014;
        }
        
        if(Protecao.isSelected()){
            seguro += 15;
        }
        
        if(SeguroVida.isSelected()){
            seguro += 22;
        }
        
        double juros = valor * taxa * meses;
        double total = valor + juros + (seguro * meses);
        double Parcela = total / meses;
        
        ValorTotal.setText("Valor total: R$ " + total);
        ValorParcela.setText("Valor da parcela: R$ " + Parcela);
    }//GEN-LAST:event_CalcularMouseClicked

