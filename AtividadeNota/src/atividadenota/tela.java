    private void buscarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buscarMouseClicked
        // TODO add your handling code here:
        try {
            String sql = "SELECT * FROM aluno WHERE id = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setInt(1, Integer.parseInt(id.getText()));
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                periodo.setText(rs.getString("periodo"));
                nomealuno.setText(rs.getString("nomealuno"));
                nomedisciplina.setText(rs.getString("nomedisciplina"));
                nota1.setText(rs.getString("nota1"));
                nota2.setText(rs.getString("nota2"));
            } else {
                JOptionPane.showMessageDialog(this, "Aluno não encontrado.");
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erro ao buscar aluno: " + e.getMessage());
        }
    }//GEN-LAST:event_buscarMouseClicked

