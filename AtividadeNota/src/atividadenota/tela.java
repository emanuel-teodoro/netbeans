    private double obterNota(javax.swing.JTextField campo){
        try{
            return Double.parseDouble(campo.getText().replace("," , "."));
        }catch(NumberFormatException e){
            return 0.0;
        }
    }
    
    private String Status(double media){
        if (media >= 7){
            return "Aprovado";
        }
        
        if(media < 4){
            return "Reprovado";
        }
        
        return "RECUPERAÇÃO";
    }
    
    private double calculomedia(double n1, double n2){
        return Math.round(((n1 + n2) / 2.0) * 100.0) / 100.0;
    }

